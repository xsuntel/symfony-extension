#!/bin/bash

set -euo pipefail
# ----------------------------------------------------------------------------------------------------------------------
# Scripts - Base - Abstract
# ----------------------------------------------------------------------------------------------------------------------

# >>>> Platform
PLATFORM_TYPE=$(uname -s)
PLATFORM_PROCESSOR=$(uname -m)

# ----------------------------------------------------------------------------------------------------------------------
# Scripts - Start
# ----------------------------------------------------------------------------------------------------------------------

setStart() {
  echo
  echo "==============================================================================================================="
  echo ">>>>  START                                                                  $(date)"
  echo "==============================================================================================================="
  echo
}

# ----------------------------------------------------------------------------------------------------------------------
# Scripts - End
# ----------------------------------------------------------------------------------------------------------------------

setEnd() {

  # >>>> Environment
  unset ENVIRONMENT_NAME

  # >>>> Platform
  unset PLATFORM_TIMEZONE

  # >>>> Project
  unset PROJECT_NAME
  unset PROJECT_PATH

  # >>>>  Utility - Git
  unset GIT_REMOTE_ORIGIN_URL
  unset GIT_CONFIG_LOCAL_USER_NAME
  unset GIT_CONFIG_LOCAL_USER_EMAIL

  # --------------------------------------------------------------------------------------------------------------------
  # Tools - VM ( Instance )
  # --------------------------------------------------------------------------------------------------------------------


  echo
  echo "==============================================================================================================="
  echo "<<<<  END                                                                    $(date)"
  echo "==============================================================================================================="
  echo
  exit 0
}

# ----------------------------------------------------------------------------------------------------------------------
# Scripts - Exit
# ----------------------------------------------------------------------------------------------------------------------

setExit() {
  echo
  echo "<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<"
  echo "  EXIT                                                                      $(date)"
  echo "<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<"
  echo
  exit 1
}
